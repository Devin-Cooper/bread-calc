#!/usr/bin/env node
// Compiles src/data/schema.json into src/core/validator.generated.ts (zero-runtime-dep validator).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const SCHEMA_PATH = "src/data/schema.json";
const OUT_PATH = "src/core/validator.generated.ts";

const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));

const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true }, strict: false });

const validators = {};
for (const [name, def] of Object.entries(schema.$defs)) {
  if (["Category", "Role", "ZoneId", "IngredientFlag", "Pct", "Factor", "ForbiddenKeys"].includes(name)) continue;
  const sub = { $defs: schema.$defs, ...def };
  ajv.addSchema(sub, name);
  validators[`validate${name}`] = name;
}

const moduleCode = standaloneCode(ajv, validators);
const banner =
  "// AUTO-GENERATED by scripts/compile-validator.mjs from src/data/schema.json. Do not edit by hand.\n" +
  "// @ts-nocheck\n" +
  "/* eslint-disable */\n";

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, banner + moduleCode);
console.error(`wrote ${OUT_PATH}`);
