#!/usr/bin/env node
// Compiles src/data/schema.json into src/core/validator.generated.ts (zero-runtime-dep validator).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const SCHEMA_PATH = "src/data/schema.json";
const OUT_PATH = "src/core/validator.generated.ts";

const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));

const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true }, strict: false, ownProperties: true });

const validators = {};
for (const [name, def] of Object.entries(schema.$defs)) {
  if (["Category", "Role", "ZoneId", "IngredientFlag", "Pct", "Factor", "ForbiddenKeys"].includes(name)) continue;
  const sub = { $defs: schema.$defs, ...def };
  ajv.addSchema(sub, name);
  validators[`validate${name}`] = name;
}

let moduleCode = standaloneCode(ajv, validators);

// Ajv's standalone generator emits ESM `export` statements (because of `code.esm: true`)
// but its scope-helper code still uses CommonJS `require(...)` for runtime helpers like
// `ajv/dist/runtime/ucs2length` and `ajv/dist/runtime/equal`. That mix breaks any
// downstream ESM bundler (Vite SSR, native node ESM). Hoist those requires to top-level
// ESM imports so the file is pure ESM.
const requireRe = /require\("(ajv\/dist\/runtime\/[^"]+)"\)\.default/g;
const requiredHelpers = new Map(); // module path -> import alias
let helperIdx = 0;
moduleCode = moduleCode.replace(requireRe, (_match, modPath) => {
  let alias = requiredHelpers.get(modPath);
  if (!alias) {
    alias = `__ajvRuntime${helperIdx++}`;
    requiredHelpers.set(modPath, alias);
  }
  return alias;
});
const importLines = Array.from(requiredHelpers.entries())
  .map(([modPath, alias]) => `import ${alias} from "${modPath}";`)
  .join("\n");

// Defense against ajv version drift: if any require(...) survived our hoist regex,
// the bundled CLI will crash with "require is not defined" at runtime. Convert to
// a build-time failure with a sample of what changed so we can update requireRe.
if (/\brequire\s*\(/.test(moduleCode)) {
  const surviving = [...moduleCode.matchAll(/\brequire\s*\([^)]+\)/g)].slice(0, 3).map((m) => m[0]).join(", ");
  throw new Error(`compile-validator: require() calls survived ESM hoist: ${surviving}. Update requireRe in scripts/compile-validator.mjs to match new ajv emitter shape.`);
}

const banner =
  "// AUTO-GENERATED by scripts/compile-validator.mjs from src/data/schema.json. Do not edit by hand.\n" +
  "// @ts-nocheck\n" +
  "/* eslint-disable */\n" +
  (importLines ? importLines + "\n" : "");

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, banner + moduleCode);
console.error(`wrote ${OUT_PATH}`);
